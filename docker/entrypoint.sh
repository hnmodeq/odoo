#!/bin/sh
# Entrypoint for the Odoo container built by ./Dockerfile.
#
# 1. Renders the Odoo config file from environment variables, so the
#    database credentials have ONE source of truth (.env / compose
#    `environment:`) shared by the `web` and `db` services. Duplicated
#    hard-coded passwords were a very common cause of
#    "Internal Server Error" (password authentication failed).
# 2. Waits until PostgreSQL really accepts connections.
# 3. Executes Odoo (or whatever command you passed).
#
# Environment variables (all optional, defaults in brackets):
#   DB_HOST [db]  DB_PORT [5432]  DB_USER [odoo]  DB_PASSWORD [odoo]
#   ADMIN_PASSWORD [admin]   master password for database management
#   ADDONS_PATH [/opt/odoo/addons]   DATA_DIR [/var/lib/odoo]
#   ODOO_CONFIG [/tmp/odoo.conf]     GENERATE_CONFIG [1]
#   PROXY_MODE [False]               set True behind Nginx/Traefik
#   WORKERS [0]                      0 = threaded (fine for dev/small use)
set -eu

DB_HOST="${DB_HOST:-db}"
DB_PORT="${DB_PORT:-5432}"
DB_USER="${DB_USER:-odoo}"
DB_PASSWORD="${DB_PASSWORD:-odoo}"
ADMIN_PASSWORD="${ADMIN_PASSWORD:-admin}"
ADDONS_PATH="${ADDONS_PATH:-/opt/odoo/addons}"
DATA_DIR="${DATA_DIR:-/var/lib/odoo}"
ODOO_CONFIG="${ODOO_CONFIG:-/tmp/odoo.conf}"
ODOO_BIN="${ODOO_BIN:-/opt/odoo/odoo-bin}"
GENERATE_CONFIG="${GENERATE_CONFIG:-1}"
export DB_HOST DB_PORT DB_USER DB_PASSWORD

# Pick up extra/custom addons if the user mounted some.
if [ -d /mnt/extra-addons ]; then
    case ",$ADDONS_PATH," in
        *,/mnt/extra-addons,*) ;;
        *) ADDONS_PATH="$ADDONS_PATH,/mnt/extra-addons" ;;
    esac
fi

if [ "$GENERATE_CONFIG" = "1" ]; then
    cat > "$ODOO_CONFIG" <<EOF
[options]
; Generated by docker/entrypoint.sh from environment variables.
; Do not edit inside the container -- change .env / compose instead.
admin_passwd = $ADMIN_PASSWORD
db_host = $DB_HOST
db_port = $DB_PORT
db_user = $DB_USER
db_password = $DB_PASSWORD
addons_path = $ADDONS_PATH
data_dir = $DATA_DIR
http_interface = 0.0.0.0
http_port = 8069
gevent_port = 8072
proxy_mode = ${PROXY_MODE:-False}
workers = ${WORKERS:-0}
list_db = True
log_level = info
EOF
    echo "entrypoint: wrote config to $ODOO_CONFIG (db: $DB_USER@$DB_HOST:$DB_PORT)"
fi

# Do not start Odoo before PostgreSQL accepts connections.
python "$(dirname "$ODOO_BIN")/docker/wait-for-psql.py"

case "${1:-odoo}" in
    odoo)
        if [ $# -gt 0 ]; then shift; fi
        exec python "$ODOO_BIN" -c "$ODOO_CONFIG" "$@"
        ;;
    -*)
        # e.g. `docker compose run --rm web -d demo -i crm --stop-after-init`
        exec python "$ODOO_BIN" -c "$ODOO_CONFIG" "$@"
        ;;
    *)
        # arbitrary command, e.g. `docker compose run --rm web bash`
        exec "$@"
        ;;
esac
